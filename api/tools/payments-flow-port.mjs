// Builds src/lib/payments-flow/model.js — the payments-flow port — from ShipLine's
// paymentsFlowMath.ts at the pinned commit (tools/payments-flow-source.mjs):
// tsc transpileModule (CommonJS, ES2022, types stripped), then the port's
// deliberate differences as exact text replacements, each of which must match
// exactly once. Nothing in model.js is written by hand.
//
// The port's differences from the TS:
//   - requires point at ./keys (paymentReviews.ts) and ./containers (containerHelpers.ts);
//   - no clock: localTodayYmd is gone, buildPaymentsFlow and bucketize require `today`;
//   - dateOfInstant reads the Europe/London calendar whatever the host's zone;
//   - buildPaymentsFlow(input, { claims: true }) also returns balanceClaims;
//   - the TS's private helpers the port's modules read are exported at the end.
//
// Run from jflow/api/ with a ShipLine checkout at the pinned commit (ShipLine has
// typescript as a devDependency; JFlow does not):
//   node tools/payments-flow-port.mjs --shipline ../../ShipLine
// Options: --check                compare with model.js instead of writing (exit 1 if stale)
//          --out <file>           write elsewhere (default src/lib/payments-flow/model.js)
//          --typescript <dir>     the typescript package to use (default <shipline>/node_modules/typescript)
//          --commit <sha>         the commit named in the header (default SOURCE.commit)
//          --allow-other-source   build from files that are not the pinned copy
// Then re-run the oracle (tools/payments-flow-oracle.mjs) and the golden tests.

/* global process, console */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { SOURCE, checkSource } from './payments-flow-source.mjs';

const MODEL_TS = 'src/components/payments/paymentsFlowMath.ts';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_OUT = path.join(HERE, '..', 'src', 'lib', 'payments-flow', 'model.js');

function fail(msg) {
    console.error(`payments-flow-port: ${msg}`);
    process.exit(1);
}

/** The header model.js starts with, naming the commit it was built from. */
export function header(commit) {
    return [
        `// Ported from ShipLine src/components/payments/paymentsFlowMath.ts @ ${commit} — changes: TS → CommonJS (tsc transpileModule, types stripped); requires point at ./keys (paymentReviews.ts) and ./containers (containerHelpers.ts); today required (no localTodayYmd fallback in buildPaymentsFlow); dateOfInstant pinned to Europe/London; buildPaymentsFlow(input, {claims: true}) also returns balanceClaims (without the option the output is the TS's); private helpers exported at the end for the port's modules. GENERATED by the re-pin script — regenerate, never hand-edit.`,
        `'use strict';`,
        `/* eslint-disable no-unused-vars -- generated from the TS as it stands; its unused locals are ShipLine's */`,
        `// This file IS the model: one transpiled copy of ShipLine's paymentsFlowMath.ts`,
        `// at the commit above, proved identical to it by api/test/unit/payments-flow-golden.test.js`,
        `// against the frozen TS's output (tools/payments-flow-oracle.mjs). The modules`,
        `// beside it (dates, lines, money, terms, suppliers, policy, due, po, flow,`,
        `// overrides) are thin re-exports of this file, kept so the rest of JFlow and`,
        `// its tests read the model by concern. Behaviour, float money arithmetic and`,
        `// rounding are the TS's — change the TS first, never just this.`,
        `//`,
        `// Display-only exports the page uses (bucketize, windowTotals, figureMembers,`,
        `// chartDensity, fmtYmd, describePolicy…) come along for free and are unused here.`,
        '',
    ].join('\n');
}

// The TS's private helpers the port's modules (lines.js, money.js, suppliers.js,
// policy.js, due.js, overrides.js) and the JFlow feed read.
export const PORT_EXPORTS = [
    'money', 'EPS', 'MIN_DERIVED', 'fmt2', 'working', 'LANDED_STATUSES', 'DEPARTED_STATUSES', 'statusOf',
    'isLandedLine', 'isDepartedLine', 'lineValueOf', 'firstDate', 'minDate', 'normName', 'looseName', 'NO_POLICY',
    'deriveGroupDue', 'applyDepositPolicy', 'applyDueOverrides', 'DERIVED_DATE_FLAGS', 'unbookedParts', 'READY_NOW_STATUSES',
];

// [what, find, replace]: each `find` must occur exactly once in the transpiled TS.
const PATCHES = [
    ['header', '"use strict";\n', null], // replaced by header(commit)
    ['no localTodayYmd export', 'exports.localTodayYmd = localTodayYmd;\n', ''],
    ['keys require', 'require("./paymentReviews")', 'require("./keys")'],
    ['containers require', 'require("../shared/containerHelpers")', 'require("./containers")'],
    ['London calendar', 'function dateOfInstant(v) {\n',
        "// The UK calendar, whatever the host's zone (Lambda runs in UTC). Port difference.\n"
        + "const LONDON_YMD = new Intl.DateTimeFormat('en-GB', {\n"
        + "    timeZone: 'Europe/London', calendar: 'gregory', numberingSystem: 'latn',\n"
        + "    year: 'numeric', month: '2-digit', day: '2-digit',\n"
        + '});\n'
        + 'function dateOfInstant(v) {\n'],
    ['dateOfInstant reads LONDON_YMD', '    return `${t.getFullYear()}-${pad2(t.getMonth() + 1)}-${pad2(t.getDate())}`;\n',
        '    const part = {};\n'
        + '    for (const p of LONDON_YMD.formatToParts(t))\n'
        + '        part[p.type] = p.value;\n'
        + '    return `${part.year}-${part.month}-${part.day}`;\n'],
    ['no localTodayYmd', 'function localTodayYmd(now = new Date()) {\n    return `${now.getFullYear()}-${pad2(now.getMonth() + 1)}-${pad2(now.getDate())}`;\n}\n',
        '// localTodayYmd (the page\'s wall-clock read) is not ported: the model never reads the clock.\n'],
    ['buildPaymentsFlow requires today', 'function buildPaymentsFlow(input) {\n    const today = dateOf(input.today) ?? localTodayYmd();\n',
        'function buildPaymentsFlow(input, options) {\n'
        + '    const today = dateOf(input.today);\n'
        + '    if (today == null)\n'
        + "        throw new TypeError(`buildPaymentsFlow: input.today is required as 'YYYY-MM-DD' (got ${JSON.stringify(input.today)})`);\n"],
    ['balanceClaims', '    const claimsByPo = new Map();\n    const addClaim = (poId, claim) => {\n',
        '    const claimsByPo = new Map();\n'
        + '    // Port addition (options.claims only): every claim as resolved, before any part-paid split.\n'
        + '    const balanceClaims = [];\n'
        + '    const addClaim = (poId, claim) => {\n'
        + '        balanceClaims.push({ shipmentPaymentId: claim.payment.id, poId, containerNumber: claim.containerNumber, source: claim.source, amount: claim.amount });\n'],
    ['return balanceClaims', '    return { today, currencies, poCount };\n',
        '    const flow = { today, currencies, poCount };\n'
        + '    if (options?.claims)\n'
        + '        flow.balanceClaims = balanceClaims;\n'
        + '    return flow;\n'],
    ['bucketize requires today', '    const today = dateOf(opts.today) ?? localTodayYmd();\n',
        '    const today = dateOf(opts.today);\n'
        + '    if (today == null)\n'
        + "        throw new TypeError('opts.today is required as \\'YYYY-MM-DD\\' (the port never reads the clock)');\n"],
];

const count = (text, find) => text.split(find).length - 1;

/**
 * model.js from the TS's text. Pure apart from the typescript module passed in.
 * @param {string} tsText  paymentsFlowMath.ts, LF line ends
 * @param {{ ts: any, commit: string }} opts
 */
export function buildModel(tsText, { ts, commit }) {
    let js = ts.transpileModule(tsText, {
        compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, removeComments: false },
    }).outputText.replace(/\r\n/g, '\n');
    for (const [what, find, replace] of PATCHES) {
        const n = count(js, find);
        if (n !== 1) throw new Error(`patch "${what}": expected its text exactly once, found it ${n} times — the TS changed there; update PATCHES`);
        js = js.replace(find, () => (replace == null ? header(commit) : replace));
    }
    // The only runtime imports are the two the port carries.
    const requires = [...js.matchAll(/require\("([^"]+)"\)/g)].map(m => m[1]);
    const unexpected = requires.filter(r => r !== './keys' && r !== './containers');
    if (unexpected.length) throw new Error(`the TS gained runtime imports the port does not carry: ${unexpected.join(', ')}`);
    // No clock anywhere (comments aside: the TS's header says "no Date.now()").
    const code = js.split('\n').filter(l => !/^\s*(\/\/|\/?\*)/.test(l)).join('\n');
    for (const clock of ['localTodayYmd(', 'Date.now(', 'new Date()']) {
        if (code.includes(clock)) throw new Error(`the transpiled TS still reads the clock: ${clock}`);
    }
    for (const name of PORT_EXPORTS) {
        if (!new RegExp(`^(?:const|let|function) ${name}\\b`, 'm').test(js)) throw new Error(`port export ${name} is no longer a top-level binding of the TS`);
        if (new RegExp(`^exports\\.${name} = `, 'm').test(js)) throw new Error(`port export ${name} is exported by the TS itself now — drop it from PORT_EXPORTS`);
    }
    js = js.replace(/\n*$/, '\n')
        + '\n// ── Port additions ──────────────────────────────────────────────────────\n'
        + '// Helpers the TS keeps private, exported for the port\'s own modules (lines.js,\n'
        + '// money.js, suppliers.js, policy.js, due.js, overrides.js) and the JFlow feed.\n'
        + PORT_EXPORTS.map(n => `exports.${n} = ${n};\n`).join('');
    return js;
}

// ── CLI ─────────────────────────────────────────────────────────────────
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const argv = process.argv.slice(2);
    const opt = (name) => {
        const i = argv.indexOf(name);
        return i === -1 ? null : (argv[i + 1] ?? fail(`${name} needs a value`));
    };
    const shipline = opt('--shipline') ?? process.env.SHIPLINE_DIR ?? fail(`--shipline <path to a ShipLine checkout at ${SOURCE.commit}> is required`);
    const out = path.resolve(opt('--out') ?? DEFAULT_OUT);
    const commit = opt('--commit') ?? SOURCE.commit;
    const check = argv.includes('--check');
    let src;
    try {
        src = checkSource(shipline, { allowOther: argv.includes('--allow-other-source') });
    } catch (e) {
        fail(e.message);
    }
    const tsDir = path.resolve(opt('--typescript') ?? path.join(shipline, 'node_modules', 'typescript'));
    if (!fs.existsSync(path.join(tsDir, 'package.json'))) fail(`no typescript package at ${tsDir} (run npm install in the ShipLine checkout, or pass --typescript)`);
    const ts = createRequire(import.meta.url)(tsDir);
    let js;
    try {
        js = buildModel(src.text[MODEL_TS], { ts, commit });
    } catch (e) {
        fail(e.message);
    }
    const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) {
        if (old !== js) fail(`${path.relative(process.cwd(), out)} is stale: rebuild it (typescript ${ts.version})`);
        console.log(`same  ${path.relative(process.cwd(), out)} (typescript ${ts.version})`);
    } else {
        if (old !== js) fs.writeFileSync(out, js);
        console.log(`${old === js ? 'same ' : 'wrote'} ${path.relative(process.cwd(), out)} from ShipLine ${commit} (typescript ${ts.version}, ${js.split('\n').length - 1} lines)`);
    }
}
