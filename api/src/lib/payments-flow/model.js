/** An uploaded invoice against what is owed. The server cannot see JFPRO
 *  terms, so this is the page's to judge: it knows each PO's deposit % and
 *  its goods in the box (`parts`). The owed figure is never changed by it. */
function compareInvoiceToOwed(a) {
    const owed = money(a.owed);
    const deducted = a.depositDeducted != null && a.depositDeducted > 0 ? a.depositDeducted : 0;
    let basis = 'balance';
    let claims = null;
    let balancePct = null;
    if (a.amountDueNow != null) {
        claims = a.amountDueNow;
    }
    else if (deducted > 0 && a.totalAmount != null) {
        // "Less 30 % deposit": the total is either the goods (gross) or already net.
        const gross = a.goodsOnBoard != null && Math.abs(a.totalAmount - a.goodsOnBoard) <= Math.max(1, a.goodsOnBoard * 0.005);
        claims = gross ? a.totalAmount - deducted : a.totalAmount;
    }
    else if (a.totalAmount != null) {
        // A goods-value invoice: its goods at the balance share the terms give.
        basis = 'goods';
        const priced = a.parts.filter(p => (p.value ?? 0) > 0);
        if (priced.length && priced.every(p => p.depositPct != null)) {
            const goods = priced.reduce((s, p) => s + p.value, 0);
            const balance = priced.reduce((s, p) => s + p.value * (1 - p.depositPct / 100), 0);
            balancePct = goods > 0 ? balance / goods : null;
            claims = balancePct != null ? a.totalAmount * balancePct : null;
        }
    }
    claims = claims == null ? null : money(claims);
    const delta = claims == null ? 0 : money(claims - owed);
    const ok = claims == null ? null : Math.abs(delta) <= Math.max(1, owed * 0.005);
    return { basis, invoiceClaims: claims, owed, delta, ok, balancePct };
}
